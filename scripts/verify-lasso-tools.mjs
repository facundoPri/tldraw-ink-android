import {chromium} from '../web/node_modules/playwright/index.mjs'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true,channel:'chrome'})
const page=await browser.newPage({viewport:{width:1204,height:752}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
async function lasso(){
 const previous=await page.evaluate(()=>window.__textRequest?.id)
 await page.mouse.move(130,550);await page.mouse.down()
 for(const [x,y] of [[600,550],[600,615],[130,615],[130,550]])await page.mouse.move(x,y,{steps:8})
 await page.mouse.up()
 await page.waitForFunction(id=>window.__textRequest?.id!==id,previous)
}
try {
 await page.addInitScript(()=>{window.TextEntry={postMessage(message){window.__textRequest=JSON.parse(message)}}})
 await page.goto('http://127.0.0.1:5179/demo.html')
 await page.waitForFunction(()=>!!window.editor)
 const initial=await page.evaluate(()=>({ids:window.editor.getCurrentPageShapes().map(s=>s.id),ink:window.editor.getCurrentPageShapes().find(s=>s.type==='draw').id}))
 await page.getByRole('button',{name:'Lasso text',exact:true}).click()
 await page.mouse.move(130,550);await page.mouse.down()
 for(const [x,y] of [[600,550],[600,615],[130,615],[130,550]])await page.mouse.move(x,y,{steps:8})
 await page.mouse.up()
 await page.waitForFunction(()=>!!window.__textRequest?.strokes)
 assert((await page.evaluate(()=>window.__textRequest.strokes.flat().length))>5)
 assert(await page.evaluate(id=>!!window.editor.getShape(id),initial.ink),'Original ink remains during recognition')
 await page.evaluate(()=>window.TextEntry.onmessage({data:JSON.stringify({id:window.__textRequest.id,text:null})}))
 await page.waitForTimeout(50)
 assert(await page.evaluate(id=>!!window.editor.getShape(id),initial.ink),'Cancel keeps original ink')
 await lasso()
 await page.evaluate(()=>window.TextEntry.onmessage({data:JSON.stringify({id:window.__textRequest.id,text:'Converted handwriting'})}))
 await page.waitForFunction(id=>!window.editor.getShape(id),initial.ink)
 assert.equal(await page.evaluate(()=>window.editor.getCurrentPageShapes().length),initial.ids.length)
 await page.evaluate(()=>{window.editor.undo()})
 assert(await page.evaluate(id=>!!window.editor.getShape(id),initial.ink),'Undo restores ink')
 // A concurrent edit must abort replacement rather than erase changed strokes.
 await lasso()
 await page.evaluate(id=>{window.editor.updateShape({id,type:'draw',x:170});window.TextEntry.onmessage({data:JSON.stringify({id:window.__textRequest.id,text:'stale result'})})},initial.ink)
 await page.waitForFunction(()=>document.body.innerText.includes('Nothing was replaced'))
 assert(await page.evaluate(id=>!!window.editor.getShape(id),initial.ink))
 await page.getByRole('button',{name:'Dismiss lasso message'}).click()
 // Configure finger Rectangle while retaining pen Draw; use real pointer routing.
 await page.getByRole('button',{name:/^Pen:/}).click()
 await page.getByRole('button',{name:'Draw — D',exact:true}).click()
 await page.getByRole('button',{name:/^Touch:/}).click()
 await page.getByRole('button',{name:'More',exact:true}).click()
 await page.getByRole('button',{name:'Rectangle — R',exact:true}).click()
 const cdp=await page.context().newCDPSession(page)
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:700,y:500,id:1}]})
 for(let i=1;i<=8;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:700+i*12,y:500+i*12,id:1}]})
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 await page.waitForFunction(()=>window.editor.getCurrentPageShapes().some(s=>s.type==='geo'&&s.x>=690&&s.y>=490))
 await cdp.send('Input.dispatchMouseEvent',{type:'mousePressed',x:700,y:620,button:'left',buttons:1,clickCount:1,pointerType:'pen'})
 assert.equal(await page.evaluate(()=>window.editor.getCurrentToolId()),'draw')
 await cdp.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:720,y:640,button:'left',buttons:0,clickCount:1,pointerType:'pen'})
 await cdp.detach()
 assert.deepEqual(errors,[])
 console.log('PASS: lasso selection, cancel, replacement, undo, concurrent edit guard, separate touch/pen tools.')
}finally{await browser.close()}
