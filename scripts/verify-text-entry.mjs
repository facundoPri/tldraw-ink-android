import {chromium} from '../web/node_modules/playwright/index.mjs'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'chrome'})
const page=await browser.newPage({viewport:{width:1204,height:752}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
 await page.addInitScript(()=>{window.TextEntry={postMessage(message){window.__textRequest=JSON.parse(message)}}})
 await page.goto(`${process.env.DESIGN_URL || 'http://127.0.0.1:5179'}/demo.html`)
 await page.waitForFunction(()=>!!window.editor)
 const before=await page.evaluate(()=>window.editor.getCurrentPageShapes().map(s=>s.id))
 await page.getByRole('button',{name:'Write text',exact:true}).click()
 assert(await page.getByRole('button',{name:'Write text',exact:true}).isDisabled())
 await page.evaluate(()=>window.TextEntry.onmessage({data:JSON.stringify({id:window.__textRequest.id,text:'Hola, tablet!\nA new note <tag> & text.'})}))
 await page.waitForFunction(()=>window.editor.getSelectedShapes()[0]?.type==='text')
 const shape=await page.evaluate(()=>window.editor.getSelectedShapes()[0])
 assert(!before.includes(shape.id));assert.equal(shape.type,'text')
 assert(JSON.stringify(shape.props.richText).includes('Hola, tablet!'))
 assert(JSON.stringify(shape.props.richText).includes('<tag> & text.'))
 await page.evaluate(()=>{window.editor.undo()})
 assert.equal(await page.evaluate(id=>!!window.editor.getShape(id),shape.id),false)
 await page.getByRole('button',{name:'Write text',exact:true}).click()
 await page.evaluate(()=>window.TextEntry.onmessage({data:JSON.stringify({id:window.__textRequest.id,text:null})}))
 await page.waitForFunction(()=>!document.querySelector('[aria-label="Write text"]').disabled)
 assert.equal(await page.evaluate(()=>window.editor.getCurrentPageShapes().length),before.length)
 await page.evaluate(()=>{window.editor.updateInstanceState({isReadonly:true})})
 assert(await page.getByRole('button',{name:'Write text',exact:true}).isDisabled())
 assert.deepEqual(errors,[])
 console.log('PASS: native text result creates literal editable text, single undo, cancel, and read-only behavior.')
} finally {await browser.close()}
